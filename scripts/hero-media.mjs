#!/usr/bin/env node
/**
 * Hero media pipeline.
 *
 * 1. Any approved originals in `media/hero-source/` are auto-oriented and
 *    written as a 1600 px WebP master into `public/images/hero/`, preserving
 *    their original aspect ratio so the hero never has to crop them.
 * 2. A tiny (24 px wide) base64 placeholder is generated for every hero
 *    image so `<Image placeholder="blur">` can paint instantly.
 *
 * Usage:
 *   npm run hero:media
 *
 * Add alt text in `app/content/hero-images.ts` afterwards. The printed
 * snippet can be pasted straight into that manifest.
 */
import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const SOURCE_DIR = path.join(ROOT, "media", "hero-source");
const OUT_DIR = path.join(ROOT, "public", "images", "hero");
const BLUR_FILE = path.join(ROOT, "app", "content", "hero-blur.generated.ts");

const MASTER_WIDTH = 1600;
const QUALITY = 84;
const IMAGE_EXT = /\.(avif|jpe?g|png|tiff?|webp)$/i;

const slug = (name) =>
  path
    .basename(name, path.extname(name))
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

async function readIfPresent(dir) {
  try {
    return await readdir(dir);
  } catch {
    return [];
  }
}

await mkdir(OUT_DIR, { recursive: true });

/* 1. Normalise fresh originals ------------------------------------------- */
const sources = (await readIfPresent(SOURCE_DIR)).filter((file) =>
  IMAGE_EXT.test(file),
);

const created = [];
for (const file of sources) {
  const input = path.join(SOURCE_DIR, file);
  const name = `${slug(file)}.webp`;
  const output = path.join(OUT_DIR, name);

  const meta = await sharp(input).metadata();
  if ((meta.width ?? 0) < 1200) {
    console.warn(
      `  ! ${file} is ${meta.width}px wide; 1600px+ sources stay sharp on high-DPI screens.`,
    );
  }

  await sharp(input)
    .rotate()
    .resize({ width: MASTER_WIDTH, withoutEnlargement: true })
    .webp({ quality: QUALITY, effort: 5 })
    .toFile(output);

  created.push(name);
  console.log(`  ✓ ${file} → public/images/hero/${name}`);
}

/* 2. Regenerate instant-paint placeholders -------------------------------- */
const heroFiles = (await readIfPresent(OUT_DIR))
  .filter((file) => IMAGE_EXT.test(file))
  .sort();

const entries = [];
for (const file of heroFiles) {
  const buffer = await sharp(path.join(OUT_DIR, file))
    .resize({ width: 24 })
    .webp({ quality: 35 })
    .toBuffer();
  entries.push([`/images/hero/${file}`, `data:image/webp;base64,${buffer.toString("base64")}`]);
}

const body = entries
  .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
  .join("\n");

await writeFile(
  BLUR_FILE,
  `// AUTO-GENERATED by scripts/hero-media.mjs — do not edit by hand.\n` +
    `// Run \`npm run hero:media\` after adding or replacing hero images.\n` +
    `export const HERO_BLUR: Record<string, string> = {\n${body}\n};\n`,
  "utf8",
);

console.log(`  ✓ ${entries.length} blur placeholders → app/content/hero-blur.generated.ts`);

if (created.length > 0) {
  console.log("\nPaste this into app/content/hero-images.ts and write real alt text:\n");
  for (const file of created) {
    console.log(
      `  { src: "/images/hero/${file}", alt: "Replace with a descriptive alt" },`,
    );
  }
  console.log("");
}
