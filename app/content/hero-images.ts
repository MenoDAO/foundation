/**
 * Home hero photo manifest.
 *
 * This file is the only place where hero photos are listed. To swap in fresh
 * field photography:
 *
 *   1. Drop the approved originals (JPG/PNG/WebP, ideally 1600 px+ wide) into
 *      `media/hero-source/`.
 *   2. Run `npm run hero:media` — it keeps each photo's original aspect ratio,
 *      writes optimised masters to `public/images/hero/`, and regenerates the
 *      blur placeholders in `hero-blur.generated.ts`.
 *   3. Update the list below with the new file names and real alt text.
 *
 * Keep the same look across the set: landscape, well-lit, people at work.
 */
import { HERO_BLUR } from "./hero-blur.generated";

export type HeroImage = {
  src: string;
  alt: string;
  /** Low-quality placeholder generated by `npm run hero:media`. */
  blurDataURL?: string;
};

const PHOTOS: Omit<HeroImage, "blurDataURL">[] = Array.from(
  { length: 16 },
  (_, i) => ({
    src: `/images/hero/gallery-${String(i + 1).padStart(2, "0")}.webp`,
    alt: `Tabasamu school and community outreach photograph ${i + 1}`,
  }),
);

export const HERO_IMAGES: HeroImage[] = PHOTOS.map((photo) => ({
  ...photo,
  blurDataURL: HERO_BLUR[photo.src],
}));
